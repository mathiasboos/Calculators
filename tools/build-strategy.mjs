#!/usr/bin/env node
// Builds the "Uttagsstrategi" tab of Retirement_Planner.html from the Typfallsmodellen web app
// (github.com/mathiasboos/Typfallsmodellen, apps/web/src/strategyPanel.ts and the engine it runs) and
// writes the result into the planner between the STRATEGY:BEGIN / STRATEGY:END markers: one <style>
// (the app's stylesheet, every selector scoped to #tab-strategy, dark mode dropped) and one <script>
// (the compiled panel, exposed as window.TFStrategy). The planner stays one file that opens offline.
//
//   node tools/build-strategy.mjs                 clones `main` of the project (shallow) into a temporary folder
//   node tools/build-strategy.mjs /path/to/clone  uses a clone you have already updated (npm ci done)
//
// Re-run it when the Typfallsmodellen project changes the strategy tab, and commit the planner.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPOSITORY = "https://github.com/mathiasboos/typfallsmodellen";
const here = dirname(fileURLToPath(import.meta.url));
const planner = resolve(here, "../Retirement_Planner.html");
const BEGIN = "<!-- STRATEGY:BEGIN";
const END = "<!-- STRATEGY:END -->";

const run = (cmd, args, cwd) => execFileSync(cmd, args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] }).trim();

let clone = process.argv[2] ? resolve(process.argv[2]) : undefined;
let temp;
if (!clone) {
  temp = mkdtempSync(join(tmpdir(), "typfall-"));
  clone = join(temp, "typfallsmodellen");
  run("git", ["clone", "--depth", "1", REPOSITORY, clone], temp);
  run("npm", ["ci", "--no-audit", "--no-fund"], clone);
}

try {
  const commit = run("git", ["rev-parse", "HEAD"], clone);
  const web = join(clone, "apps/web/src");
  const { build } = createRequire(join(clone, "package.json"))("esbuild");

  // The panel, the engine it runs and the death-probability grid, as one classic script.
  const entry = `
    import { createStrategyPanel } from "./strategyPanel.js";
    import { loadDeathProbabilities } from "./deaths.js";
    import { contextFromSettings, defaultInput, Scheme } from "@typfallsmodellen/engine";
    window.TFStrategy = { createStrategyPanel, loadDeathProbabilities, contextFromSettings, defaultInput, Scheme };
  `;
  const bundled = await build({
    stdin: { contents: entry, resolveDir: web, sourcefile: "planner-entry.ts", loader: "ts" },
    bundle: true,
    minify: true,
    format: "iife",
    target: "es2022",
    write: false,
    legalComments: "none",
  });
  const js = bundled.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");

  const css = scopeCss(readFileSync(join(web, "styles.css"), "utf8"), "#tab-strategy");

  let html = readFileSync(planner, "utf8");
  const from = html.indexOf(BEGIN);
  const to = html.indexOf(END);
  if (from < 0 || to < from) throw new Error("the STRATEGY:BEGIN / STRATEGY:END markers are missing from Retirement_Planner.html");
  const block =
    `${BEGIN} (generated by tools/build-strategy.mjs from ${REPOSITORY} ${commit.slice(0, 7)}; do not edit by hand) -->\n` +
    `<style id="strategy-css">${css}</style>\n` +
    `<script id="strategy-bundle">${js}</script>\n`;
  html = html.slice(0, from) + block + html.slice(to);
  writeFileSync(planner, html);
  console.log(`Strategy tab from ${commit.slice(0, 7)}: ${Math.round(js.length / 1024)} kB script, ${Math.round(css.length / 1024)} kB style`);
} finally {
  if (temp) rmSync(temp, { recursive: true, force: true });
}

/** Splits a selector list at top-level commas (not inside :is(...) and the like). */
function splitSelectors(list) {
  const out = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < list.length; i += 1) {
    const ch = list[i];
    if (ch === "(" || ch === "[") depth += 1;
    else if (ch === ")" || ch === "]") depth -= 1;
    else if (ch === "," && depth === 0) {
      out.push(list.slice(start, i));
      start = i + 1;
    }
  }
  out.push(list.slice(start));
  return out.map((s) => s.trim()).filter(Boolean);
}

/** One selector under the scope: the page-level ones (:root, html, body) become the scope itself. */
function scopeSelector(selector, scope) {
  const page = /^(:root|html|body)(?![\w-])/;
  if (page.test(selector)) return selector.replace(page, scope);
  return `${scope} ${selector}`;
}

/**
 * Prefixes every rule of a stylesheet with `scope`. Understands rules, @media / @supports blocks (kept,
 * their rules scoped) and @keyframes / @font-face (kept as they are). Rules that only apply in the dark
 * theme (`prefers-color-scheme: dark`, `[data-theme="dark"]`) are dropped: the planner has one theme.
 */
function scopeCss(source, scope) {
  const text = source.replace(/\/\*[\s\S]*?\*\//g, "");
  let pos = 0;

  function block(until) {
    let out = "";
    while (pos < text.length) {
      while (/\s/.test(text[pos] ?? "")) pos += 1;
      if (pos >= text.length || text[pos] === "}") {
        if (until) pos += 1;
        return out;
      }
      const open = text.indexOf("{", pos);
      const semi = text.indexOf(";", pos);
      if (semi >= 0 && (open < 0 || semi < open)) {
        out += text.slice(pos, semi + 1); // @import / @charset
        pos = semi + 1;
        continue;
      }
      const head = text.slice(pos, open).trim();
      pos = open + 1;
      if (head.startsWith("@media") || head.startsWith("@supports")) {
        const inner = block(true);
        if (!/prefers-color-scheme:\s*dark/.test(head) && inner) out += `${head}{${inner}}`;
      } else if (head.startsWith("@")) {
        const start = pos;
        let depth = 1;
        while (depth > 0) {
          if (text[pos] === "{") depth += 1;
          else if (text[pos] === "}") depth -= 1;
          pos += 1;
        }
        if (!head.startsWith("@font-face")) out += `${head}{${text.slice(start, pos - 1)}}`;
      } else {
        const end = text.indexOf("}", pos);
        const body = text.slice(pos, end).replace(/\s+/g, " ").trim();
        pos = end + 1;
        const selectors = splitSelectors(head).filter((s) => !/data-theme\s*=\s*["']?dark/.test(s));
        if (selectors.length > 0) out += `${selectors.map((s) => scopeSelector(s, scope)).join(",")}{${body}}`;
      }
    }
    return out;
  }
  return block(false);
}
